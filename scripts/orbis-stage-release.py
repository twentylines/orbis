#!/usr/bin/env python3
"""Stage a reviewed Orbis release on a Runtipi CLI v4 installation.

This writes only orbis-compose.yml. It never contacts Docker, starts services,
copies data, or changes Runtipi's Compose and user-config files.
"""

import argparse
import importlib.util
import json
import os
import re
import sys
import tempfile
from pathlib import Path


SPEC = importlib.util.spec_from_file_location("orbis_release_plan", Path(__file__).with_name("orbis-release-plan.py"))
assert SPEC and SPEC.loader
PLAN = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(PLAN)

HEADER = "# Generated by Orbis release staging. Keep custom settings in user-config/tipi-compose.yml.\n"
GENERATED = re.compile(
    r"# Generated by Orbis release staging\. Keep custom settings in user-config/tipi-compose\.yml\.\n"
    r"services:\n  runtipi:\n"
    r"    image: ghcr\.io/twentylines/orbis@sha256:[0-9a-f]{64}\n"
    r"    environment:\n"
    r"      ORBIS_VERSION: v[0-9A-Za-z.-]+\n"
    r"      ORBIS_COMMIT: [0-9a-f]{40}\n"
    r"      ORBIS_IMAGE_DIGEST: sha256:[0-9a-f]{64}\n"
)


def staged_content(manifest: dict[str, str]) -> str:
    return HEADER + PLAN.override_yaml(PLAN.validate_manifest(manifest))


def stage(root: Path, manifest: dict[str, str]) -> dict[str, object]:
    target = root / "orbis-compose.yml"
    if target.is_symlink():
        raise ValueError("orbis-compose.yml is a symlink; review it manually")
    previous = target.read_text(encoding="utf-8") if target.exists() else None
    if previous is not None and not GENERATED.fullmatch(previous):
        raise ValueError("orbis-compose.yml contains custom content; keep it and review manually")
    content = staged_content(manifest)
    if previous == content:
        return {"result": "already-staged", "override": str(target), "candidateImage": f"{PLAN.IMAGE}@{manifest['digest']}"}

    descriptor, temporary_name = tempfile.mkstemp(prefix=".orbis-compose-", suffix=".tmp", dir=root)
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, 0o644)
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
        directory = os.open(root, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        temporary.unlink(missing_ok=True)
    return {"result": "staged", "override": str(target), "candidateImage": f"{PLAN.IMAGE}@{manifest['digest']}"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path, help="Runtipi CLI v4.10.1 installation root")
    parser.add_argument("manifest", type=Path, help="reviewed release-manifest.json")
    parser.add_argument("--write", action="store_true", help="write the guarded Orbis Compose override")
    args = parser.parse_args()
    try:
        root = args.root.expanduser().resolve(strict=True)
        manifest = PLAN.validate_manifest(json.loads(args.manifest.read_text(encoding="utf-8")))
        result = PLAN.plan(root, manifest)
        if args.write:
            result.update(stage(root, manifest))
        else:
            result["result"] = "ready-to-stage"
            result["writeRequired"] = True
        print(json.dumps(result, indent=2))
        return 0
    except (OSError, ValueError, RuntimeError, json.JSONDecodeError) as error:
        print(f"Orbis staging failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
