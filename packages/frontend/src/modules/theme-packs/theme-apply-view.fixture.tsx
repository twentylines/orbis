import { expect, mock } from 'bun:test';
import type { ReactNode } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
Object.assign(globalThis, { document: { body: {} } });
mock.module('react-dom', () => ({ createPortal: (children: ReactNode) => children }));
mock.module('@/desktop/motion-preferences', () => ({ useReducedMotion: () => false }));
const { ThemeApplyCover } = await import('./theme-apply-cover');
const actions = { onRetry: () => undefined, onCancel: () => undefined };
const loading = renderToStaticMarkup(<ThemeApplyCover label="Applying theme…" {...actions} />);
expect(loading).toContain('role="dialog"');
expect(loading).toContain('aria-modal="true"');
expect(loading).toContain('aria-busy="true"');
expect(loading).toContain('background:#000');
expect(loading).toContain('aria-live="polite"');
expect(loading).not.toContain('aria-valuenow');
expect(loading.match(/class="depth-travel-plane"/g)).toHaveLength(3);
expect(loading).not.toContain('<svg');
const error = renderToStaticMarkup(<ThemeApplyCover label="Applying theme…" error="Retry safely." {...actions} />);
expect(error).toContain('role="alert"');
expect(error).toContain('aria-busy="false"');
expect(error).toContain('>Retry</button>');
expect(error).toContain('>Cancel</button>');
expect(error).toContain('data-active="false"');
process.stdout.write(JSON.stringify({ accessibilityMarkup: true, layout: false, network: false }));
